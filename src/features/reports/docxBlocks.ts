import { HeadingLevel, Paragraph, TextRun } from "docx";
import type { ReportDocument } from "../../domain/types";
import { parseAiMarkdown } from "./aiAppendix";

/** Word heading for an AI heading level; the appendix title is Heading 1. */
const APPENDIX_HEADINGS = [
  HeadingLevel.HEADING_2,
  HeadingLevel.HEADING_3,
  HeadingLevel.HEADING_4,
] as const;

/**
 * The derived report itself: one Heading 1 per non-empty category and one
 * bullet per item. Shared by the built-in document and the template renderer,
 * so both produce the same structure.
 */
export function sectionBlocks(report: ReportDocument): Paragraph[] {
  const blocks: Paragraph[] = [];
  for (const section of report.sections) {
    blocks.push(
      new Paragraph({
        text: `${section.heading}${section.categoryName}`,
        heading: HeadingLevel.HEADING_1,
      }),
    );
    for (const item of section.items) {
      blocks.push(new Paragraph({ text: item.text, bullet: { level: 0 } }));
    }
  }
  return blocks;
}

/**
 * The reviewed AI answer as a separate section after a page break. Returns an
 * empty list when there is no text, so callers can spread it unconditionally.
 */
export function aiAppendixBlocks(
  aiText: string | null | undefined,
  language: "en" | "zh-CN",
): Paragraph[] {
  const appendix = aiText?.trim();
  if (!appendix) return [];
  const blocks: Paragraph[] = [
    new Paragraph({
      text: language === "zh-CN" ? "AI 助手" : "AI assistant",
      heading: HeadingLevel.HEADING_1,
      pageBreakBefore: true,
    }),
    new Paragraph({
      children: [
        new TextRun({
          text:
            language === "zh-CN"
              ? "由 AI 生成，分享前请核对。"
              : "Generated by AI — review before sharing.",
          italics: true,
        }),
      ],
    }),
  ];
  for (const block of parseAiMarkdown(appendix)) {
    if (block.kind === "blank") {
      blocks.push(new Paragraph({ text: "" }));
    } else if (block.kind === "heading") {
      blocks.push(new Paragraph({ text: block.text, heading: APPENDIX_HEADINGS[block.level - 1] }));
    } else if (block.kind === "bullet") {
      blocks.push(new Paragraph({ text: block.text, bullet: { level: 0 } }));
    } else {
      blocks.push(new Paragraph({ text: block.text }));
    }
  }
  return blocks;
}
