import { invoke } from "@tauri-apps/api/core";
import { save } from "@tauri-apps/plugin-dialog";
import { Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import type { ReportDocument } from "../../domain/types";
import { parseAiMarkdown } from "./aiAppendix";

/** Word heading for an AI heading level; the appendix title is Heading 1. */
const APPENDIX_HEADINGS = [
  HeadingLevel.HEADING_2,
  HeadingLevel.HEADING_3,
  HeadingLevel.HEADING_4,
] as const;

/**
 * Renders a derived report into a .docx. The document intentionally keeps to
 * Word's built-in heading and bullet styles so users can restyle it from a
 * template later without Daymark owning the visual design.
 *
 * `aiText` is the reviewed text from the AI assistant. It is appended as a
 * separate, labelled section so the structured report remains the source of
 * truth and an AI answer is never presented as if Daymark had verified it.
 */
export async function exportReportDocx(
  report: ReportDocument,
  language: "en" | "zh-CN",
  aiText?: string | null,
): Promise<string | null> {
  const summary =
    language === "zh-CN"
      ? `已完成 ${report.completedCount} 项，已排期 ${report.scheduledCount} 项`
      : `${report.completedCount} completed, ${report.scheduledCount} planned`;

  const children: Paragraph[] = [
    new Paragraph({ text: report.title, heading: HeadingLevel.TITLE }),
    new Paragraph({ text: report.periodLabel, heading: HeadingLevel.HEADING_2 }),
    new Paragraph({ children: [new TextRun({ text: summary, italics: true })] }),
    new Paragraph({ text: "" }),
  ];

  for (const section of report.sections) {
    children.push(
      new Paragraph({
        text: `${section.heading}${section.categoryName}`,
        heading: HeadingLevel.HEADING_1,
      }),
    );
    for (const item of section.items) {
      children.push(
        new Paragraph({
          text: item.text,
          bullet: { level: 0 },
        }),
      );
    }
  }

  const appendix = aiText?.trim();
  if (appendix) {
    children.push(
      new Paragraph({
        text: language === "zh-CN" ? "AI 助手" : "AI assistant",
        heading: HeadingLevel.HEADING_1,
        pageBreakBefore: true,
      }),
      new Paragraph({
        children: [
          new TextRun({
            text:
              language === "zh-CN"
                ? "由 AI 生成，分享前请核对。"
                : "Generated by AI — review before sharing.",
            italics: true,
          }),
        ],
      }),
    );
    for (const block of parseAiMarkdown(appendix)) {
      if (block.kind === "blank") {
        children.push(new Paragraph({ text: "" }));
      } else if (block.kind === "heading") {
        children.push(
          new Paragraph({
            text: block.text,
            heading: APPENDIX_HEADINGS[block.level - 1],
          }),
        );
      } else if (block.kind === "bullet") {
        children.push(new Paragraph({ text: block.text, bullet: { level: 0 } }));
      } else {
        children.push(new Paragraph({ text: block.text }));
      }
    }
  }

  const document = new Document({ sections: [{ children }] });
  const blob = await Packer.toBlob(document);
  const bytes = new Uint8Array(await blob.arrayBuffer());

  const safeName = `${report.title}-${report.periodLabel}`.replace(/[\\/:*?"<>|]/g, "-");
  const target = await save({
    defaultPath: `${safeName}.docx`,
    filters: [{ name: "Word", extensions: ["docx"] }],
  });
  if (!target) return null;

  await invoke("write_file_bytes", { path: target, contents: Array.from(bytes) });
  return target;
}
